-- es = las claves; los demás, sus tablas. ru/ko/zh solo en Automático: su alfabeto solo existe en la fuente
-- de un cliente en ese idioma (en otro cliente saldrían cuadrados).
ns.Translations = { en = EN, de = DE, fr = FR, it = IT, pt = PT, ru = RU, ko = KO, zh = ZH }
ns.SelectableLanguages = {
	{ "auto", "Automático" }, { "es", "Español" }, { "en", "English" }, { "de", "Deutsch" },
	{ "fr", "Français" }, { "it", "Italiano" }, { "pt", "Português" },
}
local CLIENT = { esES = "es", esMX = "es", enUS = "en", enGB = "en", deDE = "de", frFR = "fr", itIT = "it",
	ptBR = "pt", ptPT = "pt", ruRU = "ru", koKR = "ko", zhCN = "zh" }

local function ClientLanguage() return CLIENT[GetLocale and GetLocale() or ""] or "en" end
ns.lang = ClientLanguage()

function ns.L(text, ...)
	if ns.lang ~= "es" then
		local t = ns.Translations[ns.lang]
		text = (t and t[text]) or EN[text] or text
	end
	if select("#", ...) > 0 then return text:format(...) end
	return text
end

-- "auto" (o nil: según el cliente) o un código de ns.SelectableLanguages.
function ns.SetLanguage(choice)
	ns.lang = (choice == "es" or (choice and ns.Translations[choice])) and choice or ClientLanguage()
	for i = 1, ns.MAX_PROFILES or 0 do
		_G["BINDING_NAME_" .. ns.BINDINGS[i]] = ns.L("Abrir rueda %d (mantener pulsada)", i)
	end
end
